namespace BancoAlimentar.AlimentaEstaIdeia.Model
{
    /// <summary>
    /// Defines the lifecycle state of a fiscal document.
    /// </summary>
    public enum FiscalDocumentStatus
    {
        /// <summary>
        /// The document is being prepared and is not yet fiscal evidence.
        /// </summary>
        Draft = 0,

        /// <summary>
        /// The document was issued and is immutable.
        /// </summary>
        Issued = 1,

        /// <summary>
        /// The document was cancelled while preserving its fiscal identity.
        /// </summary>
        Cancelled = 2,

        /// <summary>
        /// The document has an issued correction.
        /// </summary>
        Corrected = 3,
    }

    /// <summary>
    /// Defines the kind of fiscal document.
    /// </summary>
    public enum FiscalDocumentKind
    {
        /// <summary>
        /// The first fiscal document issued for a donation.
        /// </summary>
        Original = 0,

        /// <summary>
        /// A fiscal document that corrects a previously issued document.
        /// </summary>
        Correction = 1,

        /// <summary>
        /// A fiscal document that reverses a previously issued document.
        /// </summary>
        Credit = 2,
    }

    /// <summary>
    /// Defines the lifecycle state of a fiscal document series.
    /// </summary>
    public enum FiscalSeriesStatus
    {
        /// <summary>
        /// The series is configured but cannot issue documents.
        /// </summary>
        Draft = 0,

        /// <summary>
        /// The series can issue fiscal documents.
        /// </summary>
        Active = 1,

        /// <summary>
        /// The series is closed and cannot issue new documents.
        /// </summary>
        Closed = 2,
    }

    /// <summary>
    /// Defines the processing method communicated for a fiscal series.
    /// </summary>
    public enum FiscalProcessingMethod
    {
        /// <summary>
        /// A document generated by certified software.
        /// </summary>
        CertifiedSoftware = 0,

        /// <summary>
        /// A document generated by the AT portal.
        /// </summary>
        TaxAuthorityPortal = 1,

        /// <summary>
        /// A document generated manually under an approved contingency process.
        /// </summary>
        Manual = 2,
    }

    /// <summary>
    /// Defines whether a fiscal issuer applies to the tenant or a food bank.
    /// </summary>
    public enum FiscalScopeKind
    {
        /// <summary>
        /// The issuer applies to the whole tenant database.
        /// </summary>
        Tenant = 0,

        /// <summary>
        /// The issuer applies to one food bank.
        /// </summary>
        FoodBank = 1,
    }
}
